def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def load_pinned(name: str, path: Path, expected_sha: str,
                with_parent_path: bool = False):
    if sha256(path) != expected_sha:
        raise SystemExit(f"PINNED_MODULE_SHA_DRIFT:{name}")
    if with_parent_path:
        sys.path.insert(0, str(path.parent))
    try:
        spec = importlib.util.spec_from_file_location(name, path)
        if spec is None or spec.loader is None:
            raise SystemExit(f"PINNED_MODULE_IMPORT_FAILURE:{name}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module
    finally:
        if with_parent_path:
            sys.path.pop(0)


def identical_copies(data: bytes) -> tuple[bytes, int]:
    """Return (unit, count) with data == unit * count and count maximal."""
    if not data:
        raise RuntimeError("EMPTY_APPENDED_ARTIFACT")
    length = len(data)
    for count in range(length, 0, -1):
        if length % count:
            continue
        unit = data[:length // count]
        if unit * count == data:
            return unit, count
    raise RuntimeError("UNREACHABLE_APPENDED_ARTIFACT_DECOMPOSITION")


def require_archived_append_copies(produced: bytes, archived: bytes,
                                   count: int, label: str) -> None:
    """The archived file must be exactly `count` appended copies of produced."""
    if count < 1 or not produced or produced * count != archived:
        raise RuntimeError(f"ARCHIVED_APPEND_COPY_DISAGREEMENT:{label}:{count}")


def replace_once(text: str, old: str, new: str, label: str) -> str:
    if text.count(old) != 1:
        raise RuntimeError(f"STAGE_TEMPLATE_ANCHOR_CENSUS:{label}:{text.count(old)}")
    return text.replace(old, new, 1)


