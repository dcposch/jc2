        self.output.mkdir(parents=True, exist_ok=False)
        resume_input = json.loads(
            (self.build / "RESUME_NODE_INPUT.json").read_text())
        generators = [r5.clean_poly(value)
                      for value in resume_input["generators"]]
        if (resume_input.get("node") != 2
                or resume_input.get("inherited_rank_upper_bound") != 6
                or resume_input.get("closed_successor_of_node") != 1
                or len(generators) != 3
                or tuple(sha256_text(value) for value in generators)
                != GENERATOR_SHA256
                or tuple(resume_input.get("generator_sha256", []))
                != GENERATOR_SHA256):
            raise SystemExit("RESUME_NODE_INPUT_DRIFT")
        base = self.prepared / "r3/work/base"
        label, zeros, factor, remaining, assignment, counts = r5.source_inputs(
            base, "triple02")
        if (label != "TRIPLE02" or remaining != ["q0", "q2", "c4", "c6"]
                or r5.clean_poly(factor) != generators[0]):
            raise SystemExit("RESUME_SOURCE_RECONSTRUCTION_DRIFT")
        rank_provenance = r5.verify_rank_bound(base, "triple02", 6)
        if rank_provenance != resume_input.get("inherited_rank_provenance"):
            raise SystemExit("RESUME_RANK_PROVENANCE_DRIFT")
        delta_node1 = generators[2]
        node2_expected = (self.build / "NODE_002_REDUCE_EXPECTED.sing")
        if r5.build_reduce_script(remaining, generators, 2, label,
                                  assignment) != node2_expected.read_text():
            raise SystemExit("NODE2_REDUCE_DETERMINISM_DRIFT")
        rank_bound = 6
