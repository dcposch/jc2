#!/usr/bin/env python3
"""Experimental exact sparse extractor for the G-only production charts.

The canonical builders are generated by the frozen compiler and repaired by
the frozen ``builder_fix.py``.  They work in

    Q[y,x,all G coordinates,c], (lp(1),dp(...)),

and compute the literal P-first Jacobian ``J(P,Q)-c*x^ell``.  Their remaining
bottleneck is Singular's generic multivariate ``division`` call.  This
experiment reads (and does not change) such a repaired builder and performs
the same determinate division by the y-monic h using sparse integer
coefficient dictionaries.  No coordinate is removed, specialized, used as a
coefficient-field transcendental, or replaced by an auxiliary variable.

For completed small classes, ``--compare-native`` parses every expanded
native row into the same canonical monomial dictionary and demands literal
row equality keyed by (h power, x power, y power).  Thus the comparison is
stronger than merely comparing generated ideals.

All outputs live below experiments/fast-extract/sparse-hadic/.  This program
is not wired into the canonical solver driver.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import resource
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path
from typing import Iterable


ROOT = Path(__file__).resolve().parents[4]
GI = ROOT / "box" / "gi-only-20260905"
OUT = GI / "experiments" / "fast-extract" / "sparse-hadic"
FROZEN_BUILDER_FIX = Path("/tmp/jc2-lane.ymMTCq/inputs/builder_fix.py")
BUILDER_FIX_SHA256 = "d6662abfec114a443712600f87e3e7b7064071f445d9b177d2f0ea13c9d3836b"

# A parameter polynomial is {sorted tuple of variable numbers: Z coefficient}.
PP = dict[tuple[int, ...], int]
# A bivariate polynomial is {(x exponent, y exponent): parameter polynomial}.
BP = dict[tuple[int, int], PP]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def pp_addto(dst: PP, src: PP, scale: int = 1) -> None:
    if not scale:
        return
    for mon, coeff in src.items():
        value = dst.get(mon, 0) + scale * coeff
        if value:
            dst[mon] = value
        else:
            dst.pop(mon, None)


def merge_monomials(left: tuple[int, ...], right: tuple[int, ...]) -> tuple[int, ...]:
    """Merge two already sorted tuples without allocating a temporary sort."""
    if not left:
        return right
    if not right:
        return left
    out: list[int] = []
    i = j = 0
    while i < len(left) and j < len(right):
        if left[i] <= right[j]:
            out.append(left[i])
            i += 1
        else:
            out.append(right[j])
            j += 1
    out.extend(left[i:])
    out.extend(right[j:])
    return tuple(out)


def pp_mul(left: PP, right: PP) -> PP:
    if not left or not right:
        return {}
    out: PP = {}
    for lm, lc in left.items():
        for rm, rc in right.items():
            mon = merge_monomials(lm, rm)
            value = out.get(mon, 0) + lc * rc
            if value:
                out[mon] = value
            else:
                out.pop(mon, None)
    return out


def bp_addto(dst: BP, src: BP, scale: int = 1) -> None:
    for coord, poly in src.items():
        target = dst.setdefault(coord, {})
        pp_addto(target, poly, scale)
        if not target:
            del dst[coord]


def bp_mul(left: BP, right: BP) -> BP:
    out: BP = {}
    for (lx, ly), lp in left.items():
        for (rx, ry), rp in right.items():
            prod = pp_mul(lp, rp)
            if not prod:
                continue
            coord = (lx + rx, ly + ry)
            target = out.setdefault(coord, {})
            pp_addto(target, prod)
            if not target:
                del out[coord]
    return out


def bp_derivative(poly: BP, axis: int) -> BP:
    out: BP = {}
    for (xpow, ypow), coeff in poly.items():
        exponent = xpow if axis == 0 else ypow
        if not exponent:
            continue
        coord = (xpow - 1, ypow) if axis == 0 else (xpow, ypow - 1)
        out[coord] = {mon: exponent * value for mon, value in coeff.items()}
    return out


def bp_jac(left: BP, right: BP) -> BP:
    # Literal convention J(left,right)=left_x*right_y-left_y*right_x.
    out = bp_mul(bp_derivative(left, 0), bp_derivative(right, 1))
    bp_addto(out, bp_mul(bp_derivative(left, 1), bp_derivative(right, 0)), -1)
    return out


def bp_scaled_product(left: BP, right: BP, scale: int) -> BP:
    out = bp_mul(left, right)
    if scale != 1:
        for poly in out.values():
            for mon in list(poly):
                poly[mon] *= scale
    return out


def parse_base_polynomial(expr: str, variable_number: dict[str, int]) -> BP:
    """Parse the positive linear x,y setup emitted by the charged compiler."""
    out: BP = {}
    for raw_term in expr.split(" + "):
        xpow = ypow = 0
        parameter: int | None = None
        coefficient = 1
        for token in raw_term.split("*"):
            token = token.strip()
            match = re.fullmatch(r"([xy])(?:\^(\d+))?", token)
            if match:
                power = int(match.group(2) or 1)
                if match.group(1) == "x":
                    xpow += power
                else:
                    ypow += power
            elif re.fullmatch(r"\d+", token):
                coefficient *= int(token)
            elif token in variable_number:
                if parameter is not None:
                    raise ValueError(f"nonlinear setup term: {raw_term}")
                parameter = variable_number[token]
            else:
                raise ValueError(f"unparsed setup factor {token!r} in {raw_term!r}")
        mon = () if parameter is None else (parameter,)
        target = out.setdefault((xpow, ypow), {})
        target[mon] = target.get(mon, 0) + coefficient
    return out


def parse_expanded_parameter_polynomial(expr: str, variable_number: dict[str, int]) -> PP:
    """Parse an expanded Singular Z[parameters] polynomial exactly."""
    expr = expr.strip()
    if expr.startswith("(") and expr.endswith(")"):
        expr = expr[1:-1]
    if expr == "0":
        return {}
    # The native rows contain no parentheses or rational coefficients.
    pieces = re.findall(r"[+-]?[^+-]+", expr)
    out: PP = {}
    for piece in pieces:
        sign = -1 if piece.startswith("-") else 1
        body = piece[1:] if piece[:1] in "+-" else piece
        coefficient = sign
        variables: list[int] = []
        for factor in body.split("*"):
            if re.fullmatch(r"\d+", factor):
                coefficient *= int(factor)
                continue
            match = re.fullmatch(r"([A-Za-z_][A-Za-z_0-9]*)(?:\^(\d+))?", factor)
            if not match or match.group(1) not in variable_number:
                raise ValueError(f"bad native-row factor {factor!r}")
            variables.extend([variable_number[match.group(1)]] * int(match.group(2) or 1))
        mon = tuple(sorted(variables))
        value = out.get(mon, 0) + coefficient
        if value:
            out[mon] = value
        else:
            out.pop(mon, None)
    return out


def multiply_by_h_lower(poly: PP, hcoeff: PP) -> PP:
    # Every non-leading coefficient of the emitted h is one distinct variable.
    if len(hcoeff) != 1:
        return pp_mul(poly, hcoeff)
    (factor, scalar), = hcoeff.items()
    if len(factor) > 1:
        return pp_mul(poly, hcoeff)
    out: PP = {}
    if not factor:
        for mon, value in poly.items():
            out[mon] = value * scalar
        return out
    v = factor[0]
    for mon, value in poly.items():
        # Variable numbering is fixed; insertion is cheaper than a full sort.
        lo, hi = 0, len(mon)
        while lo < hi:
            mid = (lo + hi) // 2
            if mon[mid] <= v:
                lo = mid + 1
            else:
                hi = mid
        new_mon = mon[:lo] + (v,) + mon[lo:]
        out[new_mon] = out.get(new_mon, 0) + value * scalar
    return out


def monic_y_division(dividend: BP, h: BP, K: int) -> tuple[BP, BP]:
    """Return exact quotient,remainder for y-monic h, without term-order CAS."""
    work: BP = {coord: dict(poly) for coord, poly in dividend.items()}
    quotient: BP = {}
    lower_h = [(coord, coeff) for coord, coeff in h.items() if coord != (0, K)]
    if h.get((0, K)) != {(): 1}:
        raise AssertionError("h is not monic y^K")
    while work:
        degree_y = max(coord[1] for coord in work)
        if degree_y < K:
            break
        top = [(coord, work.pop(coord)) for coord in list(work) if coord[1] == degree_y]
        for (xpow, _), coeff in top:
            qcoord = (xpow, degree_y - K)
            target = quotient.setdefault(qcoord, {})
            pp_addto(target, coeff)
            if not target:
                del quotient[qcoord]
            # The leading y^K product is exactly the term just popped.
            for (hx, hy), hcoeff in lower_h:
                coord = (xpow + hx, degree_y - K + hy)
                product = multiply_by_h_lower(coeff, hcoeff)
                target = work.setdefault(coord, {})
                pp_addto(target, product, -1)
                if not target:
                    del work[coord]
    return quotient, work


def pp_text(poly: PP, variable_names: list[str]) -> str:
    pieces: list[str] = []
    # Deterministic degree/lex order; equality checks use dictionaries, not text.
    for mon, coefficient in sorted(poly.items(), key=lambda item: (-len(item[0]), item[0])):
        counts = Counter(mon)
        factors = [
            variable_names[number] if power == 1 else f"{variable_names[number]}^{power}"
            for number, power in sorted(counts.items())
        ]
        absolute = abs(coefficient)
        if factors:
            body = ("" if absolute == 1 else str(absolute) + "*") + "*".join(factors)
        else:
            body = str(absolute)
        if not pieces:
            pieces.append(("-" if coefficient < 0 else "") + body)
        else:
            pieces.append(("-" if coefficient < 0 else "+") + body)
    return "".join(pieces) or "0"


def count_terms(poly: BP) -> int:
    return sum(len(coeff) for coeff in poly.values())


def read_native_rows(path: Path, variable_number: dict[str, int]) -> dict[tuple[int, int, int], PP]:
    rows: dict[tuple[int, int, int], PP] = {}
    with path.open(encoding="utf-8") as fh:
        if fh.readline().rstrip("\n") != "source_index|h_power|x_power|y_power|expr":
            raise ValueError(f"bad row header: {path}")
        for line in fh:
            if not line.strip():
                continue
            _, hp, xp, yp, expr = line.rstrip("\n").split("|", 4)
            key = (int(hp), int(xp), int(yp))
            if key in rows:
                raise ValueError(f"duplicate native row coordinate {key}")
            rows[key] = parse_expanded_parameter_polynomial(expr, variable_number)
    return rows


def extract(class_id: str, compare_native: bool) -> dict:
    started = time.monotonic()
    class_dir = GI / "classes" / class_id
    cls = json.loads((class_dir / "class.json").read_text(encoding="utf-8"))
    stem = cls["canonical_stem"]
    source = class_dir / "builders" / f"{stem}_builder.sing"
    source_text = source.read_text(encoding="utf-8")
    if sha256(FROZEN_BUILDER_FIX) != BUILDER_FIX_SHA256:
        raise AssertionError("frozen builder_fix content mismatch")
    ring_match = re.search(r"^ring R=0,\((.*?)\),\(lp\(1\),dp\((\d+)\)\);$", source_text, re.M)
    if not ring_match:
        raise AssertionError("source is not a builder_fix y-first polynomial ring")
    ring_variables = ring_match.group(1).split(",")
    if ring_variables[:2] != ["y", "x"] or ring_variables[-1] != "c":
        raise AssertionError("wrong fixed-ring variable blocks")
    variable_names = ring_variables[2:]
    variable_number = {name: i for i, name in enumerate(variable_names)}
    if len(variable_names) != int(cls["unknowns_without_T"]):
        raise AssertionError("ring/meta unknown count mismatch")
    if "literal coefficient ideal: J(P,Q)" not in source_text:
        raise AssertionError("source builder is not literal P-first production")

    setup = dict(re.findall(r"^poly (h|AA\d+|BB\d+) = (.*);$", source_text, re.M))
    base = {name: parse_base_polynomial(expr, variable_number) for name, expr in setup.items()}
    K = int(cls["K"])
    e = int(cls["e"])
    q = int(cls["q"])
    ell = int(cls["ell"])
    one: BP = {(0, 0): {(): 1}}
    P = [(one, e)] + [(base[f"AA{i}"], e - i) for i in range(1, e + 1)]
    Q = [(one, q)] + [(base[f"BB{i}"], q - i) for i in range(2, q + 1)]
    if "BB1" in base:
        raise AssertionError("beta_1 unexpectedly present")

    levels: dict[int, BP] = defaultdict(dict)
    for left, r in P:
        for right, s in Q:
            bp_addto(levels[r + s], bp_jac(left, right))
            if r + s:
                lower: BP = {}
                if s:
                    bp_addto(lower, bp_scaled_product(right, bp_jac(left, base["h"]), s))
                if r:
                    bp_addto(lower, bp_scaled_product(left, bp_jac(base["h"], right), r))
                bp_addto(levels[r + s - 1], lower)

    initial_stats = {
        str(level): {"xy_coefficients": len(poly), "parameter_terms": count_terms(poly)}
        for level, poly in sorted(levels.items()) if poly
    }
    reference_path = class_dir / "rows" / f"{stem}_rows.tsv"
    reference = read_native_rows(reference_path, variable_number) if compare_native else None
    reference_keys_remaining = set(reference or {})

    out_dir = OUT / class_id
    out_dir.mkdir(parents=True, exist_ok=True)
    final_rows = out_dir / f"{stem}_sparse_rows.tsv"
    partial_rows = out_dir / f".{stem}_sparse_rows.tsv.partial.{os.getpid()}"
    row_count = total_terms = max_parameter_degree = 0
    level_stats: list[dict] = []
    mismatches: list[dict] = []
    with partial_rows.open("w", encoding="utf-8") as fh:
        fh.write("source_index|h_power|x_power|y_power|expr\n")
        level = 0
        last_initial = max(levels, default=0)
        while level <= last_initial or levels.get(level):
            before = levels.pop(level, {})
            quotient, remainder = monic_y_division(before, base["h"], K)
            if quotient:
                bp_addto(levels[level + 1], quotient)
            if level == 0:
                target = remainder.setdefault((ell, 0), {})
                pp_addto(target, {(variable_number["c"],): 1}, -1)
                if not target:
                    del remainder[(ell, 0)]
            for (xpow, ypow), poly in sorted(remainder.items()):
                key = (level, xpow, ypow)
                if reference is not None:
                    reference_keys_remaining.discard(key)
                    if reference.get(key) != poly and len(mismatches) < 10:
                        mismatches.append({
                            "key": key,
                            "native_terms": len(reference.get(key, {})),
                            "sparse_terms": len(poly),
                        })
                degree = max((len(mon) for mon in poly), default=0)
                max_parameter_degree = max(max_parameter_degree, degree)
                total_terms += len(poly)
                fh.write(f"{row_count}|{level}|{xpow}|{ypow}|{pp_text(poly, variable_names)}\n")
                row_count += 1
            level_stats.append({
                "h_power": level,
                "input_xy_coefficients": len(before),
                "input_parameter_terms": count_terms(before),
                "quotient_xy_coefficients": len(quotient),
                "quotient_parameter_terms": count_terms(quotient),
                "remainder_rows": len(remainder),
                "remainder_parameter_terms": count_terms(remainder),
            })
            level += 1
    if reference_keys_remaining:
        mismatches.append({"missing_native_keys": sorted(reference_keys_remaining)[:10]})
    comparison_passed = reference is not None and not mismatches and row_count == len(reference)
    if compare_native and not comparison_passed:
        partial_rows.unlink(missing_ok=True)
        raise AssertionError(f"native row mismatch: {mismatches[:3]}")
    os.replace(partial_rows, final_rows)

    elapsed = time.monotonic() - started
    result = {
        "schema": "moh-gi-only-sparse-hadic-extraction-experiment-v1",
        "status": "PASS",
        "class_id": class_id,
        "stem": stem,
        "production_orientation": "literal J(P,Q)-c*x^ell",
        "chart": "the full proved G_i chart; no specialization and no omitted coordinate",
        "ring": ring_match.group(0),
        "ring_from_frozen_builder_fix": True,
        "frozen_builder_fix_sha256": BUILDER_FIX_SHA256,
        "source_fixed_builder": str(source.relative_to(ROOT)),
        "source_fixed_builder_sha256": sha256(source),
        "unknowns_without_T": len(variable_names),
        "unknowns_with_T": len(variable_names) + 1,
        "coefficient_generators": row_count,
        "generator_count_including_Tc_minus_1": row_count + 1,
        "inverse_generator": "T*c-1",
        "rows": str(final_rows.relative_to(ROOT)),
        "rows_bytes": final_rows.stat().st_size,
        "rows_sha256": sha256(final_rows),
        "total_expanded_parameter_terms": total_terms,
        "max_parameter_degree": max_parameter_degree,
        "elapsed_seconds": round(elapsed, 6),
        "peak_rss_kib": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        "initial_formal_levels": initial_stats,
        "normalized_levels": level_stats,
        "exactness": {
            "jacobian_formula": "J(a*h^r,b*h^s)=h^(r+s)J(a,b)+h^(r+s-1)(s*b*J(a,h)+r*a*J(h,b))",
            "division": "top-down determinate Euclidean division by monic y^K + h_lower",
            "coefficient_domain": "Z[all original G coordinates,c] inside the required Q polynomial ring",
            "beta_1_zero": True,
            "auxiliary_variables": 0,
            "coordinate_specializations": 0,
        },
        "native_comparison": {
            "requested": compare_native,
            "reference": str(reference_path.relative_to(ROOT)) if compare_native else None,
            "reference_rows": len(reference) if reference is not None else None,
            "literal_row_dictionary_equality": comparison_passed if compare_native else None,
            "status": "PASS" if comparison_passed else ("NOT_REQUESTED" if not compare_native else "FAIL"),
        },
    }
    meta = out_dir / f"{stem}_sparse_extraction.json"
    meta.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    result["receipt"] = str(meta.relative_to(ROOT))
    return result


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--class-id", required=True)
    parser.add_argument("--compare-native", action="store_true")
    args = parser.parse_args(argv)
    result = extract(args.class_id, args.compare_native)
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
