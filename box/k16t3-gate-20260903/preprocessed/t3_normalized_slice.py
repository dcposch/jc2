@dataclasses.dataclass
class SliceRow:
    source_index: int
    h_power: int
    monomial: tuple[int, int]
    expr: sp.Expr


@dataclasses.dataclass
class KPivot:
    step: int
    source_index: int
    h_power: int
    monomial: tuple[int, int]
    variable: sp.Symbol
    coefficient: sp.Expr
    inverse: sp.Expr
    step_rhs: sp.Expr
