#!/usr/bin/env python3
"""Prepare proof-preserving q4_1=1 and quadratic-field t=3 systems.

This driver starts from the already audited constant-pivot reduction, verifies
the positive grading on every residual generator, and uses the induced G_m
action to take the q4_1=1 slice on the c != 0 locus.  It then emits both:

* an exact-Q slice retaining a Rabinowitsch equation for the image of c; and
* an exact quadratic coefficient-field system over
  Q(y)/(147*y^2-84*y+11), where y=q7_1 and c is automatically a unit.

The optional quadratic-field affine pass divides only by explicitly checked
nonzero elements of that field.  Every inverse is verified modulo the
quadratic, and every pivot substitution is checked before it is accepted.
This program prepares Singular inputs but never invokes Singular.
"""

