def verify_inputs():
    result=subprocess.run(['sha256sum','-c',str(HERE/'inputs.sha256')],capture_output=True,text=True,check=True)
    return {'all_hashes_match':True,'manifest':str(HERE/'inputs.sha256'),'transcript':result.stdout}

b.verify_inputs=verify_inputs
b.reproduce_charged_endpoint=lambda:{'scope':'historical controls executed separately; no inherited endpoint is asserted here'}

def run(branch,stage,emit_singular=None):
    result=b.run(branch,stage,emit_singular)
    result['type']='DERIVED-FACE DIAGNOSTIC OUTPUT CHART; NOT A SOURCE BRANCH VERDICT'
    result['scope']='C2/C3 source-floor inverse-map equations omitted; cannot prove a branch kill'
    result['verdict']='DIAGNOSTIC-UNIT' if result['verdict']=='DEAD' else 'DIAGNOSTIC-NONUNIT'
    result['gate_a2_zero_restriction']=GATE_A2_ZERO
    result['driver_sha256']=b.sha256(Path(__file__))
    result['source_arithmetic']=jsonable(D)
    return result

